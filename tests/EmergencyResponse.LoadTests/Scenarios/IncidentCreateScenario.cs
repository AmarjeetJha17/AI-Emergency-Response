using EmergencyResponse.Application.DTOs.Incidents;
using EmergencyResponse.LoadTests.Infrastructure;
using NBomber.CSharp;
using NBomber.Contracts;

namespace EmergencyResponse.LoadTests.Scenarios;

public static class IncidentCreateScenario
{
    public static ScenarioProps Create(LoadScenarioContext test)
    {
        var sent = 0;
        return Scenario.Create("incident-create", async _ =>
        {
            if (Interlocked.Increment(ref sent) > test.Options.IncidentCreateMaxRequests)
            {
                return NBomber.CSharp.Response.Ok(message: "Configured incident-create cap reached; no write sent.");
            }

            return await test.RequestAsync("incident.create", HttpMethod.Post, "/api/incidents", new CreateIncidentRequest
        {
            Title = $"Load test report {Guid.NewGuid():N}",
            Description = "Synthetic incident generated by the isolated load-test project.",
            IncidentTypeId = test.Data.IncidentTypeId,
            Latitude = 18.5204m,
            Longitude = 73.8567m,
            Address = "Synthetic Road",
            City = "Load Test City",
            District = "Load Test District",
            State = "Load Test State",
            PeopleAffected = 1
            }, response => response.StatusCode == System.Net.HttpStatusCode.Created);
        });
    }
}
